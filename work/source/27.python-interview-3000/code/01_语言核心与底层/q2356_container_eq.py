"""容器相等:类型门槛加逐元素递归,元素间仍用 == 比较。"""

if __name__ == "__main__":
    print("[1,2] == (1,2):", [1, 2] == (1, 2))
    print("[1,2] == [1.0,2.0]:", [1, 2] == [1.0, 2.0])
    print("[1,True] == [1,1]:", [1, True] == [1, 1])

    a = {"k": [1, {"x": 2}]}
    b = {"k": [1, {"x": 2.0}]}
    print("嵌套递归相等:", a == b)

    print("dict 顺序无关:", {"a": 1, "b": 2} == {"b": 2, "a": 1})
    print("set 相等:", {1, 2} == {2, 1, 1})

    print("严格比较要加类型门槛:", type(a) is type(b) and a == b)
