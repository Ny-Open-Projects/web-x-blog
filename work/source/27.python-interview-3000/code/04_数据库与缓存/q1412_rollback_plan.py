"""迁移回滚预案: 阶段 - 可回滚性 - 动作"""
STAGES = [
    ("仅双写 未切读", 1, "停双写即可 旧表仍是权威 零数据损失"),
    ("灰度切读中", 1, "读开关拨回旧表 秒级生效 双写继续保数据"),
    ("全量切读 旧表只读", 2, "回拨读开关 先核对停写后旧表无新依赖"),
    ("旧表已下线归档", 3, "无法快速回滚 只能逆向迁移 代价最高"),
]
for name, cost, action in STAGES:
    level = {1: "高", 2: "中", 3: "低"}[cost]
    print(f"[{level}] {name}: {action}")

read_from = "new"
print("当前读路由:", read_from, end=" -> 发现异常回拨: ")
read_from = "old"
print(read_from, "<- 秒级生效 不影响写路径")
print("纪律: 每推进一个阶段前 先确认上一阶段的回滚动作依然可用")
